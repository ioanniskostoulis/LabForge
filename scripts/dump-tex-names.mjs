// Writes source/app/tex-names.ts: every command name (letters only) that exists once labforge.cls has loaded under
// LuaLaTeX, which is the set the editor accepts without a definition. Run it after the class loads other packages:
//   node scripts/dump-tex-names.mjs
import { spawnSync } from "node:child_process";
import { cpSync, existsSync, mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { delimiter, join } from "node:path";

const texbin = ["/Library/TeX/texbin", "/opt/homebrew/bin", "/usr/local/bin"].find(dir => existsSync(join(dir, "lualatex")));
const env = { ...process.env, PATH: `${texbin ?? ""}${delimiter}${process.env.PATH ?? ""}` };
const folder = mkdtempSync(join(tmpdir(), "labforge-names-"));
cpSync("assets/framework/labforge.cls", join(folder, ".labforge.cls"));
writeFileSync(join(folder, "dump.lua"), `local names = {}
for _, entry in pairs(tex.hashtokens()) do
  local name = type(entry) == "table" and entry[1] or entry
  if type(name) == "string" and name:match("^%a+$") then names[#names + 1] = name end
end
table.sort(names)
local file = io.open("names.txt", "w"); file:write(table.concat(names, " ")); file:close()
`);
writeFileSync(join(folder, "dump.tex"), "\\documentclass[bibliography]{.labforge}\n\\begin{document}\n\\directlua{dofile(\"dump.lua\")}\nx\n\\end{document}\n");
const run = spawnSync("lualatex", ["-interaction=nonstopmode", "dump.tex"], { cwd: folder, env, encoding: "utf8" });
if (!existsSync(join(folder, "names.txt"))) { console.error(run.stdout.slice(-2000)); process.exit(1); }
const names = readFileSync(join(folder, "names.txt"), "utf8");
writeFileSync("source/app/tex-names.ts", `// Licensed under the GNU General Public License v2 or later. See LICENSE.
// Generated by scripts/dump-tex-names.mjs from LuaLaTeX with labforge.cls loaded; do not edit by hand.
// Every command name made of letters that exists in a LabForge report, so the editor can tell a misspelling from a command.

const names = ${JSON.stringify(names)};
export const texCommandNames: ReadonlySet<string> = new Set(names.split(" "));
`);
console.log(`${names.split(" ").length} command names written to source/app/tex-names.ts`);
