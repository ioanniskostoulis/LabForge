import { contextBridge, ipcRenderer, webUtils } from "electron";
import type { MenuState } from "../app/menu-definition";

contextBridge.exposeInMainWorld("labforge", {
  platform: process.platform,
  listOpen: () => ipcRenderer.invoke("project:list-open"),
  create: () => ipcRenderer.invoke("project:new"),
  open: () => ipcRenderer.invoke("project:open"),
  openPath: (file: string) => ipcRenderer.invoke("project:open-path", file),
  pathForFile: (file: File) => webUtils.getPathForFile(file),
  activate: (id: string) => ipcRenderer.invoke("project:activate", id),
  save: (id: string) => ipcRenderer.invoke("project:save", id),
  configure: (id: string, patch: { name?: string; builder?: "xelatex" | "pdflatex" | "lualatex" }) => ipcRenderer.invoke("project:configure", id, patch),
  close: (id: string) => ipcRenderer.invoke("project:close", id),
  files: (id: string) => ipcRenderer.invoke("project:files", id),
  read: (id: string, file: string) => ipcRenderer.invoke("project:read", id, file),
  copyText: (text: string) => ipcRenderer.invoke("app:copy-text", text),
  misspelledWords: (words: string[]) => ipcRenderer.invoke("spell:check", words),
  wordSuggestions: (word: string) => ipcRenderer.invoke("spell:suggest", word),
  addWord: (word: string) => ipcRenderer.invoke("spell:add", word),
  ignoreWord: (word: string) => ipcRenderer.invoke("spell:ignore", word),
  commandInputSource: (action: "begin" | "restore") => { ipcRenderer.send("app:command-input-source", action); return true; },
  commandInputContext: (active: boolean) => ipcRenderer.send("app:command-input-context", active),
  write: (id: string, file: string, content: string) => ipcRenderer.invoke("project:write", id, file, content),
  rename: (id: string, from: string, to: string) => ipcRenderer.invoke("project:rename", id, from, to),
  mkdir: (id: string, folder: string) => ipcRenderer.invoke("project:mkdir", id, folder),
  copy: (id: string, from: string, to: string) => ipcRenderer.invoke("project:copy", id, from, to),
  setTitleBar: (colors: { color: string; symbolColor: string }) => ipcRenderer.send("setTitleBar", colors),
  add: (id: string, folder: string) => ipcRenderer.invoke("project:add", id, folder),
  addDropped: (id: string, folder: string, files: File[]) => ipcRenderer.invoke("project:add-paths", id, folder, files.map(file => webUtils.getPathForFile(file)).filter(Boolean)),
  external: (id: string, file: string) => ipcRenderer.invoke("project:external", id, file),
  reveal: (id: string, file: string) => ipcRenderer.invoke("project:reveal", id, file),
  trash: (id: string, file: string) => ipcRenderer.invoke("project:trash", id, file),
  exportZip: (id: string) => ipcRenderer.invoke("project:export", id),
  contents: (id: string) => ipcRenderer.invoke("project:contents", id),
  pdf: (id: string) => ipcRenderer.invoke("project:pdf", id),
  build: (id: string) => ipcRenderer.invoke("project:build", id),
  sourceAt: (id: string, page: number, x: number, y: number) => ipcRenderer.invoke("project:source-at", id, page, x, y),
  pdfAt: (id: string, file: string, line: number) => ipcRenderer.invoke("project:pdf-at", id, file, line),
  checkTex: (builder: "xelatex" | "pdflatex" | "lualatex") => ipcRenderer.invoke("app:check-tex", builder),
  openLink: (url: string) => ipcRenderer.invoke("app:open-link", url),
  cancelBuild: (id: string) => ipcRenderer.invoke("project:cancel-build", id),
  generated: (id: string, kind: "plot" | "table") => ipcRenderer.invoke("generated:list", id, kind),
  regenerate: (id: string, files: string[]) => ipcRenderer.invoke("generated:regenerate", id, files),
  createGenerated: (id: string, settings: unknown) => ipcRenderer.invoke("generated:create", id, settings),
  pickSpreadsheet: (id: string) => ipcRenderer.invoke("generated:pick", id),
  sheets: (id: string, source: string) => ipcRenderer.invoke("generated:sheets", id, source),
  generatedCode: (id: string, settings: unknown) => ipcRenderer.invoke("generated:code", id, settings),
  saveGenerated: (id: string, kind: "plot" | "table", code: string, source?: string) => ipcRenderer.invoke("generated:save", id, kind, code, source),
  previewGenerated: (id: string, kind: "plot" | "table", code: string, keys?: string) => ipcRenderer.invoke("generated:preview", id, kind, code, keys),
  rewriteGenerated: (id: string, file: string, settings: unknown) => ipcRenderer.invoke("generated:rewrite", id, file, settings),
  onOpened: (callback: (project: unknown) => void) => ipcRenderer.on("project:opened", (_event, project) => callback(project)),
  onChanged: (callback: (project: unknown) => void) => ipcRenderer.on("project:changed", (_event, project) => callback(project)),
  onError: (callback: (id: string, error: string) => void) => ipcRenderer.on("project:error", (_event, id, error) => callback(id, error)),
  onCommand: (callback: (id: string) => void) => ipcRenderer.on("app:command", (_event, id) => callback(id)),
  updateMenuState: (state: MenuState) => ipcRenderer.send("app:menu-state", state),
  onCloseRequest: (callback: () => void) => ipcRenderer.on("app:close-request", callback),
  onFullScreen: (callback: (on: boolean) => void) => ipcRenderer.on("fullScreen", (_event, on: boolean) => callback(on)),
  closeReady: () => ipcRenderer.send("app:close-ready"),
  closeCancel: () => ipcRenderer.send("app:close-cancel"),
  installUpdate: (asset: unknown) => ipcRenderer.invoke("installUpdate", asset),
});
